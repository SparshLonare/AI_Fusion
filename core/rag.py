import json
import logging
import os
import time
from pathlib import Path
import chromadb
from google import genai
from google.genai import types
from pypdf import PdfReader

_client = None
CHROMA_DB_PATH = os.environ.get(
    "CHROMA_DB_PATH", str(Path(__file__).resolve().parent.parent / "chroma_db")
)
col = chromadb.PersistentClient(path=CHROMA_DB_PATH).get_or_create_collection(
    "docs", metadata={"hnsw:space": "cosine"})

EMBED_MODEL = "gemini-embedding-001"
LLM_MODEL = "gemini-3.8-flash"
FALLBACK_MODELS = ["gemini-flash-latest", "gemini-3.5-flash-lite"]
MIN_SCORE = 0.45                 # tune this during testing
logger = logging.getLogger(__name__)


def _get_client():
    global _client
    if _client is None:
        api_key = os.environ.get("GEMINI_API_KEY")
        if not api_key:
            raise RuntimeError("Set the GEMINI_API_KEY environment variable to use Gemini.")
        _client = genai.Client(api_key=api_key)
    return _client


def _is_retryable_generation_error(error):
    """Return whether an SDK error represents rate limiting or a server error."""
    status_code = getattr(error, "status_code", None) or getattr(error, "code", None)
    try:
        status_code = int(status_code)
    except (TypeError, ValueError):
        return False
    return status_code == 429 or 500 <= status_code <= 599


def _generate_content(contents, config):
    """Try the primary model and configured fallbacks with transient retries."""
    retry_delays = (1, 2, 4)
    last_error = None
    gemini_client = _get_client()
    for model in [LLM_MODEL, *FALLBACK_MODELS]:
        for attempt in range(len(retry_delays) + 1):
            try:
                response = gemini_client.models.generate_content(
                    model=model, contents=contents, config=config
                )
                logger.info("Gemini response generated by model %s", model)
                return response
            except Exception as error:
                last_error = error
                if not _is_retryable_generation_error(error):
                    logger.warning(
                        "Gemini model %s failed with a non-retryable error; trying fallback if available",
                        model,
                    )
                    break
                if attempt == len(retry_delays):
                    logger.warning("Gemini model %s failed after retries", model)
                    break
                delay = retry_delays[attempt]
                logger.warning(
                    "Gemini model %s returned a retryable error; retrying in %s seconds",
                    model,
                    delay,
                )
                time.sleep(delay)
    raise last_error


def embed(texts):
    res = _get_client().models.embed_content(model=EMBED_MODEL, contents=texts)
    return [e.values for e in res.embeddings]

def chunk(text, size=800, overlap=150):
    out, i = [], 0
    while i < len(text):
        out.append(text[i:i + size])
        i += size - overlap
    return out


def extract(file):
    if file.name.lower().endswith(".pdf"):
        return [(p.extract_text() or "", n + 1) for n, p in enumerate(PdfReader(file).pages)]
    return [(file.read().decode("utf-8", "ignore"), 1)]


def ingest(file):
    ids, docs, metas = [], [], []
    for text, page in extract(file):
        for j, c in enumerate(chunk(text)):
            ids.append(f"{file.name}-{page}-{j}")
            docs.append(c)
            metas.append({"source": file.name, "page": page})
    for i in range(0, len(docs), 90):
        b = slice(i, i + 90)
        col.upsert(ids=ids[b], documents=docs[b], metadatas=metas[b], embeddings=embed(docs[b]))
    return len(docs)


def retrieve(query, k=5):
    r = col.query(query_embeddings=embed([query]), n_results=k)
    hits = [{"text": d, **m, "score": round(1 - dist, 3)}
            for d, m, dist in zip(r["documents"][0], r["metadatas"][0], r["distances"][0])]
    return [h for h in hits if h["score"] >= MIN_SCORE]


def list_sources():
    result = col.get(include=["metadatas"])
    return sorted({
        metadata["source"]
        for metadata in (result.get("metadatas") or [])
        if metadata and metadata.get("source")
    })


PROMPT = """You are a programming tutor. Use ONLY the numbered documentation context
to make documentation-based claims. If the context doesn't cover the problem,
say so in "kb_coverage" instead of inventing documentation claims.

Return JSON with keys:
explanation (string), issues (list of {{line_hint, problem, why}}),
corrected_code (string), used_sources (list of context numbers you relied on),
kb_coverage ("full" | "partial" | "none").

CONTEXT:
{context}

USER PROBLEM: {problem}

USER CODE:
{code}
"""

def explain(code, problem):
    hits = retrieve(f"{problem}\n{code}"[:2000])
    context = "\n\n".join(
        f"[{i+1}] ({h['source']}, p.{h['page']})\n{h['text']}" for i, h in enumerate(hits)
    ) or "NO RELEVANT DOCUMENTATION FOUND."
    resp = _generate_content(
        contents=PROMPT.format(context=context, problem=problem, code=code),
        config=types.GenerateContentConfig(response_mime_type="application/json"),
    )
    return {"result": json.loads(resp.text), "sources": hits}
